/** Artifact categories with a retention bound. */
export type RetentionCategoryType =
	| 'benchmark_workspace'
	| 'benchmark_scratch_database'
	| 'benchmark_project_checkout'
	| 'evaluation_workspace'
	| 'evaluation_report'
	| 'evidence_bundle';

/** Why a retention candidate is retained or refused. */
export type RetentionReasonType = 'required_bundle' | 'suite_needs_checkout' | 'within_bound' | 'protected_path' | 'dirty_worktree' | 'active_owner';

/** One removable retention candidate. */
export type RetentionTargetType = Readonly<{
	readonly category: RetentionCategoryType;
	readonly path: string;
	readonly bytes: number;
}>;

/** One candidate that was not collected, with the reason it was kept. */
export type RetentionDecisionType = Readonly<{
	readonly category: RetentionCategoryType;
	readonly path: string;
	readonly bytes: number;
	readonly reason: RetentionReasonType;
}>;

/** Retention candidates, refusals, retained entries, and worktree roots to prune. */
export type RetentionPlanType = Readonly<{
	readonly targets: readonly RetentionTargetType[];
	readonly refused: readonly RetentionDecisionType[];
	readonly retained: readonly RetentionDecisionType[];
	readonly worktreeRoots: readonly string[];
}>;

/** Root and policy input shared by the retention collectors. */
export type RetentionInputType = Readonly<{
	readonly protectedPaths: readonly string[];
	readonly now?: Date | undefined;
	readonly discardDirty?: boolean | undefined;
}>;
